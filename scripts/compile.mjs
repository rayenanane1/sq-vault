// Compiles contracts/SQRecoveryModule.sol with solc-js and writes src/lib/recoveryArtifact.ts
import solc from 'solc'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const file = 'SQRecoveryModule.sol'
const input = {
  language: 'Solidity',
  sources: { [file]: { content: fs.readFileSync(path.join(root, 'contracts', 'src', file), 'utf8') } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
}
const findImports = (p) => {
  const full = path.join(root, 'node_modules', p)
  return fs.existsSync(full) ? { contents: fs.readFileSync(full, 'utf8') } : { error: 'not found ' + p }
}
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }))
const errors = (out.errors || []).filter((e) => e.severity === 'error')
if (errors.length) { console.error(errors.map((e) => e.formattedMessage).join('\n')); process.exit(1) }
const c = out.contracts[file].SQRecoveryModule
const ts = `// Auto generated by scripts/compile.mjs. Do not edit.
export const recoveryModuleAbi = ${JSON.stringify(c.abi, null, 2)} as const

export const recoveryModuleBytecode = '0x${c.evm.bytecode.object}' as const
`
fs.mkdirSync(path.join(root, 'src/lib'), { recursive: true })
fs.writeFileSync(path.join(root, 'src/lib/recoveryArtifact.ts'), ts)
console.log('compiled, bytecode bytes:', c.evm.bytecode.object.length / 2)
